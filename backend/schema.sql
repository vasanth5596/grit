-- Supabase uses PostgreSQL. The FastAPI SQLAlchemy models create this schema
-- automatically for the prototype; this file is the equivalent deployable DDL.
create table if not exists students (
  id text primary key,
  name text not null,
  email text not null unique,
  badge text not null,
  eligible boolean not null default true,
  skills_cleared integer not null default 4,
  skills_required integer not null default 4,
  created_at timestamptz not null default now()
);

create table if not exists interviewers (
  id text primary key,
  name text not null,
  email text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists availability_slots (
  id bigint generated by default as identity primary key,
  interviewer text not null,
  date date not null,
  start time not null,
  "end" time not null,
  status text not null default 'open' check (status in ('open', 'booked', 'blocked'))
);

create index if not exists ix_availability_date_status on availability_slots (date, status);

create table if not exists bookings (
  id bigint generated by default as identity primary key,
  student_id text not null references students(id),
  slot_id bigint not null references availability_slots(id),
  status text not null default 'booked' check (status in ('booked', 'completed', 'cancelled')),
  outcome text check (outcome in ('pass', 'fail', 'retake')),
  feedback text,
  booked_at timestamptz not null default now(),
  completed_at timestamptz
);

create unique index if not exists uq_bookings_active_slot
  on bookings (slot_id) where status = 'booked';
create unique index if not exists uq_bookings_active_student
  on bookings (student_id) where status = 'booked';
create index if not exists ix_bookings_status on bookings (status);
